export function getCityName(city: City, locale: Locale) {
  if (locale === 'zh') return city.name
  if (locale === 'zh-hant') return traditionalCityNames[city.id] ?? city.name
  return englishCityNames[city.id] ?? city.name
}

export function getCountryName(city: City, locale: Locale) {
  if (locale === 'zh') return city.country
  if (locale === 'zh-hant') return traditionalCountryNames[city.country] ?? city.country
  return englishCountryNames[city.country] ?? city.country
}

export function getCitySearchText(city: City) {
  return [
    city.name,
    traditionalCityNames[city.id],
    englishCityNames[city.id],
    city.country,
    traditionalCountryNames[city.country],
    englishCountryNames[city.country],
    city.timeZone,
  ]
    .filter(Boolean)
    .join(' ')
    .toLocaleLowerCase()
}
